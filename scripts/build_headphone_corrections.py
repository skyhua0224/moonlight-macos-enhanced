#!/usr/bin/env python3
"""Build the headphone correction list the audio settings search.

Reads the parametric equalizer results of the AutoEq project
(https://github.com/jaakkopasanen/AutoEq, MIT license) and writes one line per
headphone to Limelight/macOS/Supporting Files/HeadphoneCorrections.tsv:

    name <TAB> form <TAB> source <TAB> preamp <TAB> filters

where filters is "K frequency gain q" joined by ";" and K is P (peak),
L (low shelf) or H (high shelf).

A headphone measured by several sources is listed once, from the source
highest in SOURCE_ORDER (measurement rigs closest to the current standards
first).

Usage:
  git clone --filter=blob:none --no-checkout --depth 1 https://github.com/jaakkopasanen/AutoEq.git
  cd AutoEq && git sparse-checkout set --no-cone /LICENSE '/results/**/*ParametricEQ.txt' && git checkout
  build_headphone_corrections.py path/to/AutoEq
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Limelight", "macOS", "Supporting Files", "HeadphoneCorrections.tsv")
SUFFIX = " ParametricEQ.txt"

SOURCE_ORDER = [
    "oratory1990",
    "crinacle/GRAS 43AG-7 over-ear",
    "crinacle/Bruel & Kjaer 4620 in-ear",
    "Rtings/Bruel & Kjaer 5128",
    "HypetheSonics/Bruel & Kjaer 5128",
    "crinacle/711 in-ear",
    "HypetheSonics/GRAS RA0045 in-ear",
    "Rtings",
    "Innerfidelity",
    "Super Review",
    "HypetheSonics",
    "Kuulokenurkka",
    "crinacle",
]
LAST_SOURCE = "Headphone.com Legacy"

FILTER = re.compile(
    r"^Filter\s*\d+:\s*ON\s+(PK|LSC|HSC)\s+Fc\s+([\d.]+)\s*Hz\s+Gain\s+(-?[\d.]+)\s*dB\s+Q\s+([\d.]+)")
PREAMP = re.compile(r"^Preamp:\s*(-?[\d.]+)\s*dB")
KIND = {"PK": "P", "LSC": "L", "HSC": "H"}


def rank(source, rig):
    key = f"{source}/{rig}"
    for index, prefix in enumerate(SOURCE_ORDER):
        if key.startswith(prefix):
            return index
    return len(SOURCE_ORDER) + (1 if source == LAST_SOURCE else 0)


def form_of(rig):
    for form in ("over-ear", "in-ear", "earbud"):
        if rig.endswith(form):
            return form
    return ""


def number(text):
    value = float(text)
    return ("%.2f" % value).rstrip("0").rstrip(".")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    repo = sys.argv[1]
    results = os.path.join(repo, "results")
    best = {}
    for directory, _, files in os.walk(results):
        for file in files:
            if not file.endswith(SUFFIX):
                continue
            parts = os.path.relpath(directory, results).split(os.sep)
            if len(parts) != 3:
                continue
            source, rig, name = parts
            preamp, filters = "0", []
            with open(os.path.join(directory, file), encoding="utf-8") as handle:
                for line in handle:
                    match = PREAMP.match(line)
                    if match:
                        preamp = number(match.group(1))
                        continue
                    match = FILTER.match(line)
                    if match:
                        filters.append(" ".join(
                            [KIND[match.group(1)]] + [number(match.group(i)) for i in (2, 3, 4)]))
            if not filters or "\t" in name:
                continue
            entry = (rank(source, rig), source, name, form_of(rig), preamp, ";".join(filters))
            key = name.casefold()
            if key not in best or entry[:2] < best[key][:2]:
                best[key] = entry

    commit = subprocess.run(
        ["git", "-C", repo, "log", "-1", "--format=%h %cs"], capture_output=True, text=True
    ).stdout.strip()
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
        out.write(f"# Headphone corrections from AutoEq ({commit}), https://github.com/jaakkopasanen/AutoEq\n")
        out.write("# Generated by scripts/build_headphone_corrections.py. The AutoEq license follows.\n#\n")
        # The license asks for its text to travel with copies, so it stays with the data.
        with open(os.path.join(repo, "LICENSE"), encoding="utf-8") as handle:
            for line in handle.read().strip().splitlines():
                out.write(("# " + line).rstrip() + "\n")
        for _, source, name, form, preamp, filters in sorted(best.values(), key=lambda e: e[2].casefold()):
            out.write("\t".join([name, form, source, preamp, filters]) + "\n")
    print(f"{len(best)} headphones -> {os.path.relpath(OUTPUT, ROOT)} ({os.path.getsize(OUTPUT) // 1024} KiB)")


if __name__ == "__main__":
    main()
