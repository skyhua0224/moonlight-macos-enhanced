#!/usr/bin/env python3
"""Cuts Sunshine's real Windows touch code out of src/platform/windows/input.cpp, so the replay runs the code the
host runs and not a copy of it: from `struct client_input_raw_t` (the per-client state) up to, not including, the
doc comment of pen_update. That holds client_input_raw_t, perform_touch_compaction, pointer_by_id,
populate_common_pointer_info, repeat_touch, cancel_all_active_touches and touch_update.

usage: extract.py <input.cpp> <out.inc>
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
start = src.index("  struct client_input_raw_t: public client_input_t {")
end_marker = re.search(r"\n  /\*\*\n   \* @brief Sends a pen event to the OS\.", src)
assert end_marker and end_marker.start() > start, "pen_update marker not found: the source layout changed"
body = src[start:end_marker.start()]
for needed in ("perform_touch_compaction", "pointer_by_id", "populate_common_pointer_info", "touch_update",
               "cancel_all_active_touches", "repeat_touch", "Unexpected new pointer"):
    assert needed in body, f"{needed} missing from the extracted range"
open(sys.argv[2], "w", encoding="utf-8").write("// generated by extract.py from %s\n%s\n" % (sys.argv[1], body))
print("extracted %d lines" % body.count("\n"))
